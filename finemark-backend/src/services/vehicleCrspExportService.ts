import { vehicleAll } from "../vehicleDb.js";

export interface CrspExportFilter {
  make?: string;
  source?: string;
}

// Escapes a value for embedding inside a single-quoted-free, double-quoted JS
// object literal exactly like the hand-authored car-models.js does (plain
// double quotes around string values, no extra escaping beyond that).
const jsString = (value: string): string => `"${value.replace(/"/g, '\\"')}"`;

/**
 * Builds the exact car-models.js file text from approved, KRA-numbered vehicle
 * master rows — restricted to source IN ('kra_crsp','manual_csv') because
 * modelNumber there carries KRA's own valuation-model-number semantics that
 * the certificate/registration workflows already depend on; rows sourced from
 * NHTSA/JATO/CarMD/DataOne have no comparable numbering scheme and are
 * deliberately excluded from this export.
 */
export async function buildCrspExport(filter: CrspExportFilter = {}): Promise<{ fileText: string; rowCount: number }> {
  const conditions = [`status = 'approved'`, `source IN ('kra_crsp', 'manual_csv')`];
  const params: any[] = [];
  if (filter.make) { conditions.push(`make = ?`); params.push(filter.make); }
  if (filter.source) { conditions.push(`source = ?`); params.push(filter.source); }

  const rows = await vehicleAll<{ make: string; model: string; trim: string | null; source_ref: string; body_style: string | null }>(
    `SELECT make, model, trim, source_ref, body_style FROM vehicle_specs
     WHERE ${conditions.join(" AND ")}
     ORDER BY make, model`,
    params
  );

  const lines: string[] = [];
  lines.push(`// Finemark — Vehicle make/model/model-number/body-type data`);
  lines.push(`// Source: KRA CRSP listing (KES) + manually curated entries`);
  lines.push(`// Generated by the Vehicle Data Sync admin page — ${rows.length} entries`);
  lines.push(`// Format: { make, model, modelNumber, bodyType }`);
  lines.push(`const CAR_MODELS_DATA = [`);

  let currentMake: string | null = null;
  for (const row of rows) {
    if (row.make !== currentMake) {
      currentMake = row.make;
      const divider = `// ── ${currentMake} `.padEnd(70, "─");
      lines.push(`  ${divider}`);
    }
    const modelText = row.trim ? `${row.model} ${row.trim}` : row.model;
    lines.push(
      `  {make:${jsString(row.make)},model:${jsString(modelText)},modelNumber:${jsString(row.source_ref || "")},bodyType:${jsString(row.body_style || "")}},`
    );
  }

  lines.push(`];`);
  lines.push(``);
  lines.push(`// ── Helpers ──────────────────────────────────────────────────────────────────`);
  lines.push(`function carGetMakes() {`);
  lines.push(`  return [...new Set(CAR_MODELS_DATA.map(r => r.make))].sort();`);
  lines.push(`}`);
  lines.push(`function carGetModels(make) {`);
  lines.push(`  return [...new Set(`);
  lines.push(`    CAR_MODELS_DATA.filter(r => r.make === make).map(r => r.model)`);
  lines.push(`  )].sort();`);
  lines.push(`}`);
  lines.push(`function carGetModelNumbers(make, model) {`);
  lines.push(`  return CAR_MODELS_DATA`);
  lines.push(`    .filter(r => r.make === make && r.model === model && r.modelNumber)`);
  lines.push(`    .map(r => r.modelNumber);`);
  lines.push(`}`);
  lines.push(`function carGetBodyType(make, model) {`);
  lines.push(`  const entry = CAR_MODELS_DATA.find(r => r.make === make && r.model === model);`);
  lines.push(`  return entry ? entry.bodyType : '';`);
  lines.push(`}`);

  return { fileText: lines.join("\n") + "\n", rowCount: rows.length };
}
